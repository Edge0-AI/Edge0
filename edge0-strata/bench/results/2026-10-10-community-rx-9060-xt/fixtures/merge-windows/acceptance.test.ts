import test from 'node:test';
import assert from 'node:assert/strict';
import {mergeWindows} from './windows.ts';
const w=(start:number,end:number)=>({start,end});
test('empty',()=>assert.deepEqual(mergeWindows([]),[]));
test('one',()=>assert.deepEqual(mergeWindows([w(1,2)]),[w(1,2)]));
test('sort input',()=>assert.deepEqual(mergeWindows([w(5,6),w(1,2)]),[w(1,2),w(5,6)]));
test('overlap',()=>assert.deepEqual(mergeWindows([w(1,4),w(3,7)]),[w(1,7)]));
test('touching',()=>assert.deepEqual(mergeWindows([w(1,3),w(3,5)]),[w(1,5)]));
test('containment',()=>assert.deepEqual(mergeWindows([w(1,10),w(2,3),w(8,12)]),[w(1,12)]));
test('same start',()=>assert.deepEqual(mergeWindows([w(1,8),w(1,3)]),[w(1,8)]));
test('duplicate',()=>assert.deepEqual(mergeWindows([w(1,2),w(1,2)]),[w(1,2)]));
test('exact gap',()=>assert.deepEqual(mergeWindows([w(1,2),w(4,5)],2),[w(1,5)]));
test('outside gap',()=>assert.deepEqual(mergeWindows([w(1,2),w(4,5)],1),[w(1,2),w(4,5)]));
test('gap chains',()=>assert.deepEqual(mergeWindows([w(8,9),w(1,2),w(4,6)],2),[w(1,9)]));
test('negative coordinates',()=>assert.deepEqual(mergeWindows([w(-4,-1),w(-2,3)]),[w(-4,3)]));
test('fractional coordinates',()=>assert.deepEqual(mergeWindows([w(.5,1.25),w(1.5,2)],.25),[w(.5,2)]));
test('zero length',()=>assert.deepEqual(mergeWindows([w(2,2),w(1,2)]),[w(1,2)]));
test('frozen input',()=>{const a=Object.freeze([Object.freeze(w(3,5)),Object.freeze(w(1,4))]); assert.deepEqual(mergeWindows(a as any),[w(1,5)]);});
test('new objects and unchanged input',()=>{const a=[w(3,5),w(1,4)]; const old=structuredClone(a);const b=mergeWindows(a);assert.deepEqual(a,old);assert.ok(b.every(x=>!a.includes(x)));});
for(const gap of [-1,NaN,Infinity,-Infinity]) test('bad gap '+gap,()=>assert.throws(()=>mergeWindows([],gap),RangeError));
for(const pair of [[2,1],[NaN,1],[0,Infinity],[-Infinity,0],[0,NaN]]) test('bad window '+pair,()=>assert.throws(()=>mergeWindows([w(pair[0],pair[1])]),RangeError));
