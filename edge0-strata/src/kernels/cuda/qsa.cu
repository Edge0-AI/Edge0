// src/kernels/cuda/qsa.cu - P2.S2: the QSA cache, indexer and attention (see include/strata/kernels/qsa.hpp).
//
// The header documents the layouts and the scope; this file documents the four decisions that are about the
// KERNEL rather than about the interface.
//
// 1. THE THRESHOLD SEARCH IN `topk_512` RATHER THAN A SORT.  The selection has to reproduce `ggml_top_k` on the
//    masked per-cell scores with the reference's tie rule (ascending index), and it has to be EXACT: a
//    different selected set is a different attention input, and `docs/capture-format.md` L127 gives
//    `indexer_ids` no tolerance.  The kernel therefore computes the width-th largest score as a 32-bit
//    "order key" by binary lifting (32 monotone passes with `count(key >= cand) >= width`), and then emits -
//    in ONE ascending walk - every cell strictly above it and the first `width - c_gt` cells equal to it.  That
//    is provably the same set as sorting by (score desc, index asc) and taking the first width, it needs no
//    scratch and no sort, it is deterministic, and it is the reason `kTopkMaxCells` exists: the whole selection
//    runs in ONE block so the ascending walk is a chunked scan rather than a second global pass.  Phase 3
//    replaces it with a radix select; this one is the thing that radix select has to agree with.
//
// 2. ONE BLOCK PER HEAD IN `qsa_attend`, SCORES IN SHARED MEMORY.  n_ids reaches 2051, so a per-head score
//    vector is 8 KB and 24 heads are 24 blocks: the whole attention is 24 blocks x 256 threads, which is a
//    small grid, but it is also exactly the shape the source uses (one flash tile per query head) and it keeps
//    the softmax's three passes over the scores in shared memory instead of in global.  The score loop has one
//    thread per CELL walking the 256 dims sequentially, which reads 16-byte-vectorisable half2 runs; the value
//    loop has one thread per DIM walking the cells, whose warp-wide reads are contiguous within a cell.  Both
//    are coalesced for the layout the gather produces.
//
// 3. NO `__float2half`.  `f16_from_f32` from f16_bits.hpp, for the reason round 193 recorded: `__float2half`
//    produced 0x2600 for 0x26DB and 0x3C01 for exactly 1.0.  The parity test checks that converter against
//    vectors generated by numpy's float16, which is an oracle sharing no code with it.
//
// 4. THE POOLING ARITHMETIC IS IN DOUBLE AND ORDER-FIXED.  `pooled` and the spare key are compared BIT-EXACT
//    against the reference (the spare key's rotation is at position 0, where the f32 rope kernel is an exact
//    identity, so the comparison is not weakened by the rope).  That needs the same summation order on both
//    sides: the `r` raw keys are added in CELL order, the sum of squares runs d = 0..idx_dim-1 sequentially,
//    and `__dadd_rn`/`__dmul_rn` block FMA contraction, which would otherwise fuse `ss + m*m` into one
//    operation with no intermediate rounding and land one ulp away from the host.
//
//    THE `d` IN THOSE NAMES IS NOT COSMETIC.  The first version wrote `__fadd_rn`/`__fmul_rn`, which are
//    the SINGLE-precision intrinsics: the compiler converted each double operand to float, operated
//    there, and converted back, so the whole pooling arithmetic ran in single precision - `ss` held only
//    float precision (121.82236480712891 on the device against 121.82236342931094 in the reference).
//    Every comparison still passed at any sane tolerance, the spare key landing 0.4 f32 ulp away; only a
//    BIT-EXACT assertion plus a full-precision probe of the intermediate found it.  That is the strongest
//    argument in this file for keeping both.
