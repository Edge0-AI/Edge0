//! TypeScript binding generator: `cargo run -p edge0-core --bin gen-ts -- <out-dir>`.

use std::path::Path;

use ts_rs::{Config, TS};

fn cfg() -> Config {
    // On-wire u64 values stay below 2^53, so JS number is safe; bigint would need conversion.
    Config::new().with_large_int("number")
}

fn write_ts(dir: &Path, ty: &str, content: &str) {
    std::fs::write(dir.join(format!("{ty}.ts")), content).unwrap_or_else(|e| {
        panic!("failed to write {ty}.ts: {e}");
    });
}

fn ts<T: TS + 'static>(name: &str) -> String {
    T::export_to_string(&cfg()).unwrap_or_else(|e| panic!("failed to generate {name}: {e}"))
}

fn main() {
    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| panic!("usage: gen-ts <out-dir>"));
    let dir = Path::new(&out);
    std::fs::create_dir_all(dir).expect("out-dir");

    use edge0_core::protocol as p;
    let dep = dir.join("serde_json");
    std::fs::create_dir_all(&dep).expect("serde_json dir");
    std::fs::write(
        dep.join("JsonValue.ts"),
        ts::<serde_json::Value>("JsonValue"),
    )
    .unwrap();
    write_ts(dir, "Event", &ts::<p::Event>("Event"));
    write_ts(dir, "HelloPayload", &ts::<p::HelloPayload>("HelloPayload"));
    write_ts(
        dir,
        "ResyncPayload",
        &ts::<p::ResyncPayload>("ResyncPayload"),
    );
    write_ts(
        dir,
        "SystemSnapshot",
        &ts::<p::SystemSnapshot>("SystemSnapshot"),
    );
    write_ts(dir, "DaemonInfo", &ts::<p::DaemonInfo>("DaemonInfo"));
    write_ts(dir, "HardwareInfo", &ts::<p::HardwareInfo>("HardwareInfo"));
    write_ts(dir, "ModelEntry", &ts::<p::ModelEntry>("ModelEntry"));
    write_ts(
        dir,
        "DownloadEntry",
        &ts::<p::DownloadEntry>("DownloadEntry"),
    );
    write_ts(
        dir,
        "DownloadFailure",
        &ts::<p::DownloadFailure>("DownloadFailure"),
    );
    write_ts(dir, "CatalogTier", &ts::<p::CatalogTier>("CatalogTier"));
    write_ts(
        dir,
        "CatalogResponse",
        &ts::<p::CatalogResponse>("CatalogResponse"),
    );

    use edge0_core::conversation as c;
    write_ts(dir, "Role", &ts::<c::Role>("Role"));
    write_ts(
        dir,
        "MessageStatus",
        &ts::<c::MessageStatus>("MessageStatus"),
    );
    write_ts(dir, "Usage", &ts::<c::Usage>("Usage"));
    write_ts(dir, "Attachment", &ts::<c::Attachment>("Attachment"));
    write_ts(
        dir,
        "MessageRecord",
        &ts::<c::MessageRecord>("MessageRecord"),
    );
    write_ts(dir, "ThreadRecord", &ts::<c::ThreadRecord>("ThreadRecord"));

    let union: Vec<String> = p::EVENT_TYPES.iter().map(|t| format!("\"{t}\"")).collect();
    let folded: Vec<String> = p::EVENT_TYPES
        .iter()
        .filter(|t| p::foldable(t))
        .map(|t| format!("\"{t}\""))
        .collect();
    std::fs::write(
        dir.join("EventType.ts"),
        format!(
            "// Generated by gen-ts; do not edit.\nexport type EventType = {}; \
             \nexport const FOLDED_EVENT_TYPES: EventType[] = [{}];\n",
            union.join(" |\n  "),
            folded.join(", ")
        ),
    )
    .unwrap();

    let names = [
        "Event",
        "HelloPayload",
        "ResyncPayload",
        "SystemSnapshot",
        "DaemonInfo",
        "HardwareInfo",
        "ModelEntry",
        "DownloadEntry",
        "DownloadFailure",
        "CatalogTier",
        "CatalogResponse",
        "EventType",
        "Role",
        "MessageStatus",
        "Usage",
        "Attachment",
        "MessageRecord",
        "ThreadRecord",
    ];
    std::fs::write(
        dir.join("index.ts"),
        format!(
            "// Generated by gen-ts; do not edit.\n{}\n",
            names
                .iter()
                .map(|n| format!("export * from \"./{n}\";\n"))
                .collect::<Vec<_>>()
                .join(""),
        ),
    )
    .unwrap();

    println!("gen-ts: wrote {dir:?}");
}
